import assert from "node:assert/strict";
import { createRequire } from "node:module";
import fs from "node:fs";
import { createServer } from "vite";
import { MemoryRouter } from "react-router-dom";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { accessGroups, inviteRoles, overrideValue, setOverride, lifecycleLabel } from "./src/components/teamAccessPresentation.js";
const require = createRequire(import.meta.url);
const { CAPABILITIES, effectivePermissions } = require("../backend/authorization/capabilities.js");
const identifiers = accessGroups.flatMap(([, items]) => items.map(([id]) => id));
assert.deepEqual([...identifiers].sort(), [...CAPABILITIES].sort(), "Every control maps to exactly one existing capability");
assert.equal(new Set(identifiers).size, identifiers.length);
assert(inviteRoles(["owner"]).includes("owner"));
for (const role of ["admin", "coach", "closer", "member", "viewer", "ambassador"]) assert(!inviteRoles([role]).includes("owner"));
let overrides = { allow: [], deny: [] };
overrides = setOverride(overrides, "analytics.view", "allow");
assert(effectivePermissions({ roles: ["coach"], role: "coach", permissionOverrides: overrides }).includes("analytics.view"));
overrides = setOverride(overrides, "analytics.view", "deny");
assert.equal(overrideValue(overrides, "analytics.view"), "deny");
assert(!effectivePermissions({ roles: ["admin"], role: "admin", permissionOverrides: overrides }).includes("analytics.view"));
overrides = setOverride(overrides, "analytics.view", "default");
assert.deepEqual(overrides, { allow: [], deny: [] });
assert.deepEqual(setOverride(overrides, "fake.permission", "allow"), overrides);
assert.equal(lifecycleLabel({ status: "invited", invitation: { status: "ready" } }), "Invite ready");
const source = fs.readFileSync("src/components/TeamAccess.jsx", "utf8");
assert(source.includes("Manage access")); assert(source.includes("availableRoles.map"));
assert(!source.includes("Effective access:")); assert(!source.includes("What each role means")); assert(!source.includes("effectivePermissions.join"));
assert(source.includes("Send invitation")); assert(source.includes("setOverride("));
console.log("Team & Access roles, complete canonical permission mapping, override precedence, defaults and invitation UI passed.");
const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: "custom" });
try {
  const { default: TeamAccess } = await server.ssrLoadModule("/src/components/TeamAccess.jsx");
  const render = roles => renderToStaticMarkup(createElement(MemoryRouter, null, createElement(TeamAccess, { canManage: true, actorRoles: roles })));
  assert(render(["owner"]).includes("Owner / Business Owner"));
  assert(!render(["admin"]).includes("Owner / Business Owner"));
  assert(render(["owner"]).includes("Create invite preview"));
  assert(!render(["owner"]).includes("crm.view"));
  console.log("Actual TeamAccess component: Owner/Admin invite choices and readable initial UI passed.");
} finally { await server.close(); }
